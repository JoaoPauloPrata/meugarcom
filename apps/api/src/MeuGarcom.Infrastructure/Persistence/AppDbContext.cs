using MeuGarcom.Application.Common.Interfaces;
using MeuGarcom.Domain.Accounts;
using MeuGarcom.Domain.Ai;
using MeuGarcom.Domain.Conversations;
using MeuGarcom.Domain.Menus;
using Microsoft.EntityFrameworkCore;

namespace MeuGarcom.Infrastructure.Persistence;

/// <summary>
/// Maps the domain to the Supabase Postgres schema. The schema itself is owned by the SQL
/// migrations in supabase/migrations (applied through the Supabase MCP), not by EF migrations.
/// </summary>
public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options), IAppDbContext
{
    public DbSet<Account> Accounts => Set<Account>();
    public DbSet<Restaurant> Restaurants => Set<Restaurant>();
    public DbSet<Unit> Units => Set<Unit>();
    public DbSet<DiningTable> DiningTables => Set<DiningTable>();
    public DbSet<Menu> Menus => Set<Menu>();
    public DbSet<MenuCategory> MenuCategories => Set<MenuCategory>();
    public DbSet<MenuItem> MenuItems => Set<MenuItem>();
    public DbSet<MenuImport> MenuImports => Set<MenuImport>();
    public DbSet<Conversation> Conversations => Set<Conversation>();
    public DbSet<ConversationMessage> ConversationMessages => Set<ConversationMessage>();
    public DbSet<GuardrailEvent> GuardrailEvents => Set<GuardrailEvent>();
    public DbSet<AiModelSettings> AiModelSettings => Set<AiModelSettings>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema("public");
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Ids are generated by the domain (UUID v7). Without this, EF would treat new child
        // entities added through a navigation as existing rows and issue UPDATEs.
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            var id = entityType.FindProperty("Id");
            if (id is not null)
                id.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never;
        }
    }
}
